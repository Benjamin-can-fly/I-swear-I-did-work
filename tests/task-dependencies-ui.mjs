import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {chromium} from '@playwright/test';

const day='2026-11-05',at=day+'T16:00:00+08:00',port=43352,base='http://127.0.0.1:'+port;
const dir=await mkdtemp(path.join(tmpdir(),'worklog-chain-ui-'));
const server=spawn(process.execPath,['server/index.js'],{windowsHide:true,env:{...process.env,PORT:String(port),DATA_DIR:dir,WORKLOG_CAPTURE_HOME:path.join(dir,'no-model')},stdio:'pipe'});
const task=(id,title,extra={})=>({id,title,notes:'',project:'',due:day,dueTime:'20:00',scheduledDate:day,status:'next',priority:'normal',recordId:'',createdAt:at,startedAt:at,completedAt:'',autoSyncRecord:false,...extra});
const read=async()=>(await(await fetch(base+'/api/data')).json()).data;
let browser;
try{
 await once(server.stdout,'data');assert.equal((await(await fetch(base+'/api/status')).json()).dataDirectory,dir);
 const response=await fetch(base+'/api/data',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({revision:0,data:{version:1,records:[],tasks:[task('a','写作文'),task('b','检查作文',{afterTaskId:'a'}),task('missing','缺失前一步的后续任务',{afterTaskId:'deleted'})]}})});assert.equal(response.status,200,await response.text());
 browser=await chromium.launch({channel:'msedge',headless:true});const page=await browser.newPage({timezoneId:'Asia/Shanghai',reducedMotion:'reduce'}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.clock.install({time:new Date(at)});await page.goto(base);
 const today=id=>page.locator('#today-content [data-today-task="'+id+'"]');
 await today('b').waitFor();assert.equal(await today('b').locator('.task-check').isDisabled(),true);
 assert.equal(await today('b').locator('.today-task-title').isDisabled(),true);
 assert.match(await today('b').textContent(),/前一步：\s*写作文/);
 assert.equal(await page.locator('[data-today-stat=pending] strong').textContent(),'1');
 assert.match(await page.locator('#today-content .urgency-summary').textContent(),/1 项/);
 await today('a').locator('.task-check').click();
 await page.waitForFunction(()=>document.querySelector('[data-today-task="b"] .today-task-title')===document.activeElement);
 assert.equal(await today('b').locator('.task-check').isEnabled(),true);assert.match(await page.locator('#toast').textContent(),/下一步：检查作文/);
 assert.equal((await read()).tasks.find(t=>t.id==='a').status,'done');
 await page.getByRole('button',{name:'撤销',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-today-task="b"] .task-check')?.disabled);
 assert.equal((await read()).tasks.find(t=>t.id==='a').status,'next');
 await page.reload();await today('b').waitFor();assert.equal(await today('b').locator('.task-check').isDisabled(),true);
 await page.locator('.sidebar [data-page=tasks]').click();
 const row=id=>page.locator('#tasks [data-task="'+id+'"]');
 assert.equal(await row('b').locator('.task-check').isDisabled(),true);assert.equal(await row('b').locator('.task-writing').isDisabled(),true);
 assert.equal(await row('b').getAttribute('data-urgency'),'neutral');assert.equal(await row('b').locator('[data-countdown]').count(),0);
 await row('b').locator('[data-entry-menu]').click();assert.equal(await page.getByRole('menuitem',{name:'标记完成',exact:true}).count(),0);
 await page.getByRole('menuitem',{name:'修改',exact:true}).click();
 const form=page.locator('#task-form'),relation=form.locator('[name=afterTaskId]');
 await relation.waitFor();assert.equal(await relation.inputValue(),'a');assert.equal(await relation.locator('option[value="b"]').count(),0);
 await form.locator('.cancel-edit').click();
 await row('missing').locator('[data-entry-menu]').click();await page.getByRole('menuitem',{name:'修改',exact:true}).click();
 assert.equal(await relation.inputValue(),'deleted');assert.match(await relation.locator('option:checked').textContent(),/前一步已删除/);
 await relation.selectOption('');await page.reload();await page.locator('.sidebar [data-page=tasks]').click();await form.locator('.expand-fields').click();
 await relation.waitFor();assert.equal(await relation.inputValue(),'','explicit detach survives draft reload instead of restoring the stale link');
 await form.locator('[type=submit]').click();await page.waitForFunction(async()=>(await(await fetch('/api/data')).json()).data.tasks.find(t=>t.id==='missing')?.afterTaskId==='');
 assert.equal(await row('missing').locator('.task-check').isEnabled(),true);assert.equal(await relation.isVisible(),false,'new capture stays compact');
 assert.deepEqual(errors,[]);console.log('PASS: waiting items and neutral deadlines, blocked controls, direct next-step focus, undo/reload, full-list predecessor choices, missing link detach and recovered edit draft.');
}finally{await browser?.close();server.kill();}
